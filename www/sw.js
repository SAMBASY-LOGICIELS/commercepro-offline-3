// Service worker (version Android / navigateur). Inutile dans l'.exe (file://).
// IMPORTANT : changer CACHE_NAME à chaque nouvelle version pour forcer la mise à jour.
const CACHE_NAME = "commerce-pro-v4-3";
const CORE_FILES = [
  "./",
  "./index.html",
  "./manifest.json",
  "./brand-banner.jpg",
  "./icon-192.png",
  "./icon-512.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(CORE_FILES)));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  // Ne jamais intercepter les requêtes externes (ex. synchronisation ntfy.sh) :
  // sinon l'ancienne réponse en cache serait renvoyée à la place des données à jour.
  if (new URL(req.url).origin !== self.location.origin) return;

  event.respondWith(
    caches.match(req).then((cached) => {
      if (cached) return cached;
      return fetch(req)
        .then((res) => {
          if (res && res.ok) {
            const copy = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(req, copy));
          }
          return res;
        })
        .catch(() => (req.mode === "navigate" ? caches.match("./index.html") : Response.error()));
    })
  );
});
